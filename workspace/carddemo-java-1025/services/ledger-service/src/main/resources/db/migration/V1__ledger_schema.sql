-- 总账分录（ADR-010）：按 entry_group_id 幂等，同一分组只允许一组分录
CREATE TABLE ledger_entry_group (
    entry_group_id  VARCHAR(64) PRIMARY KEY,
    business_type   VARCHAR(40) NOT NULL,
    reference_id    VARCHAR(64) NOT NULL,
    line_count      INT         NOT NULL,
    created_at      TIMESTAMP   NOT NULL
);

CREATE TABLE ledger_entry_line (
    line_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_group_id  VARCHAR(64)    NOT NULL REFERENCES ledger_entry_group (entry_group_id),
    account_code    VARCHAR(40)    NOT NULL,
    direction       VARCHAR(8)     NOT NULL,
    amount          NUMERIC(12, 2) NOT NULL,
    memo            VARCHAR(120)
);

CREATE INDEX idx_ledger_line_group ON ledger_entry_line (entry_group_id);
CREATE INDEX idx_ledger_line_account ON ledger_entry_line (account_code);
