-- 本轮返工（A-R001..A-R005 / R-C-01 / R-C-03）
-- 1) 通知发件箱 INSERT 失败时的真实补偿队列（独立表，避免失败污染主事务）
CREATE TABLE installment_notification_retry (
    retry_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel          VARCHAR(16)  NOT NULL,
    recipient        VARCHAR(64)  NOT NULL,
    template         VARCHAR(40)  NOT NULL,
    payload          VARCHAR(2000),
    last_error       VARCHAR(200),
    created_at       TIMESTAMP    NOT NULL
);

-- 2) 还款在途查询（A-R003：未完成还款阻止结清）
CREATE INDEX idx_installment_repayment_status ON installment_repayment (plan_id, status);

-- 3) 对账扫描（停滞还款/结清意图）
CREATE INDEX idx_installment_repayment_updated ON installment_repayment (updated_at);
CREATE INDEX idx_installment_settlement_status ON installment_settlement_intent (plan_id, status);
