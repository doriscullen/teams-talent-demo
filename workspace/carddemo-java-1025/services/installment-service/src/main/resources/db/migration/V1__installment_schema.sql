-- REQ-2026-001 分期上下文数据库（ADR-010）
-- 定价/策略参数（BR-INS-01/02/07/11），不硬编码在代码里
CREATE TABLE installment_policy (
    id                            SMALLINT      PRIMARY KEY,
    min_transaction_amount        NUMERIC(12, 2) NOT NULL,
    min_bill_amount               NUMERIC(12, 2) NOT NULL,
    max_active_plans_per_account  INT           NOT NULL,
    penalty_rate                  NUMERIC(6, 4) NOT NULL,
    preview_ttl_minutes           INT           NOT NULL,
    idempotency_window_minutes    INT           NOT NULL,
    updated_at                    TIMESTAMP     NOT NULL
);

CREATE TABLE installment_rate (
    term_months       INT           PRIMARY KEY,
    monthly_fee_rate  NUMERIC(6, 4) NOT NULL
);

CREATE TABLE installment_plan (
    plan_id                     VARCHAR(32)    PRIMARY KEY,
    account_id                  VARCHAR(11)    NOT NULL,
    customer_id                 VARCHAR(9),
    source_type                 VARCHAR(16)    NOT NULL,
    source_id                   VARCHAR(32)    NOT NULL,
    principal                   NUMERIC(12, 2) NOT NULL,
    term_months                 SMALLINT       NOT NULL,
    monthly_fee_rate            NUMERIC(6, 4)  NOT NULL,
    total_fee                   NUMERIC(12, 2) NOT NULL,
    remaining_principal         NUMERIC(12, 2) NOT NULL,
    status                      VARCHAR(16)    NOT NULL,
    created_at                  TIMESTAMP      NOT NULL,
    settled_at                  TIMESTAMP,
    idempotency_key             VARCHAR(64)    NOT NULL,
    settlement_idempotency_key  VARCHAR(64),
    version                     BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_installment_plan_idempotency UNIQUE (idempotency_key)
);

CREATE INDEX idx_installment_plan_account ON installment_plan (account_id, status);
CREATE INDEX idx_installment_plan_source ON installment_plan (source_type, source_id);

CREATE TABLE installment_schedule (
    schedule_id     VARCHAR(40)    PRIMARY KEY,
    plan_id         VARCHAR(32)    NOT NULL REFERENCES installment_plan (plan_id),
    installment_no  SMALLINT       NOT NULL,
    due_date        DATE           NOT NULL,
    principal_due   NUMERIC(12, 2) NOT NULL,
    fee_due         NUMERIC(12, 2) NOT NULL,
    total_due       NUMERIC(12, 2) NOT NULL,
    status          VARCHAR(16)    NOT NULL,
    paid_at         TIMESTAMP,
    CONSTRAINT uk_installment_schedule UNIQUE (plan_id, installment_no)
);

-- 本金级去重（BR-INS-09）：每条记录代表「某笔已入账交易的本金已被某计划占用」
CREATE TABLE installment_principal_allocation (
    allocation_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id           VARCHAR(32)    NOT NULL REFERENCES installment_plan (plan_id),
    transaction_id    VARCHAR(16)    NOT NULL,
    principal_amount  NUMERIC(12, 2) NOT NULL
);

CREATE INDEX idx_installment_allocation_txn ON installment_principal_allocation (transaction_id);

-- 持卡人—账户可访问关系（真实归属来源，不信任请求体自报）
CREATE TABLE installment_account_access (
    account_id  VARCHAR(11) NOT NULL,
    user_id     VARCHAR(8)  NOT NULL,
    PRIMARY KEY (account_id, user_id)
);

-- 后台身份区分：STAFF_ASSIST=客服可协助写；RISK_READONLY=风控只读（AC-21）
CREATE TABLE installment_permission (
    user_id     VARCHAR(8)  NOT NULL,
    permission  VARCHAR(32) NOT NULL,
    PRIMARY KEY (user_id, permission)
);

-- 单账户并发闸门（20 笔上限在持锁事务内计数，BR-INS-11）
CREATE TABLE installment_account_lock (
    account_id VARCHAR(11) PRIMARY KEY
);

-- 逾期/争议信号（基线缺失，由本设计补齐；AC-17）
CREATE TABLE installment_eligibility_flag (
    transaction_id  VARCHAR(16) PRIMARY KEY,
    disputed        BOOLEAN     NOT NULL DEFAULT FALSE,
    delinquent      BOOLEAN     NOT NULL DEFAULT FALSE,
    updated_at      TIMESTAMP   NOT NULL
);

-- 提前结清幂等意图（同键重放 200、异键 409，AC-16）
CREATE TABLE installment_settlement_intent (
    settlement_key  VARCHAR(64)    PRIMARY KEY,
    plan_id         VARCHAR(32)    NOT NULL,
    principal       NUMERIC(12, 2) NOT NULL,
    penalty_fee     NUMERIC(12, 2) NOT NULL,
    fee_rebate      NUMERIC(12, 2) NOT NULL,
    amount          NUMERIC(12, 2) NOT NULL,
    status          VARCHAR(24)    NOT NULL,
    updated_at      TIMESTAMP      NOT NULL
);

-- 后台导出文件（24 小时有效，US-008）
CREATE TABLE installment_export_file (
    export_id     VARCHAR(40) PRIMARY KEY,
    requested_by  VARCHAR(8)  NOT NULL,
    row_count     INT         NOT NULL,
    content       TEXT        NOT NULL,
    created_at    TIMESTAMP   NOT NULL,
    expires_at    TIMESTAMP   NOT NULL
);

CREATE TABLE installment_audit_event (
    audit_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor          VARCHAR(8)  NOT NULL,
    action         VARCHAR(40) NOT NULL,
    resource_type  VARCHAR(32) NOT NULL,
    resource_id    VARCHAR(64) NOT NULL,
    payload        VARCHAR(2000),
    created_at     TIMESTAMP   NOT NULL
);

CREATE TABLE installment_audit_retry (
    retry_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor          VARCHAR(8),
    action         VARCHAR(40),
    resource_type  VARCHAR(32),
    resource_id    VARCHAR(64),
    payload        VARCHAR(2000),
    last_error     VARCHAR(200),
    created_at     TIMESTAMP   NOT NULL
);

-- 通知失败不回滚主流程（A-05）：先落发件箱，失败可补发
CREATE TABLE installment_notification_outbox (
    notification_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel          VARCHAR(16)  NOT NULL,
    recipient        VARCHAR(64)  NOT NULL,
    template         VARCHAR(40)  NOT NULL,
    payload          VARCHAR(2000),
    status           VARCHAR(16)  NOT NULL,
    attempts         INT          NOT NULL DEFAULT 0,
    last_error       VARCHAR(200),
    created_at       TIMESTAMP    NOT NULL
);
